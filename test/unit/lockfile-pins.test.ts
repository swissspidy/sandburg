/**
 * The versions a pnpm-lock.yaml or yarn.lock pins (src/adapters/node/lockfile-pins.ts, ADR 0063),
 * and how the install plan applies them (local-packages.ts).
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { lockPins } from '../../src/adapters/node/lockfile-pins.ts';
import { installPlan } from '../../src/adapters/node/local-packages.ts';
import type { PackageJson } from '../../src/types.ts';

const PNPM_9 = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      react:
        specifier: ^18.2.0
        version: 18.2.0
      react-dom:
        specifier: ^18.2.0
        version: 18.2.0(react@18.2.0)
      '@acme/ui':
        specifier: workspace:*
        version: link:packages/ui
    devDependencies:
      vite:
        specifier: ^5.0.0
        version: 5.4.0

  packages/ui:
    dependencies:
      ms:
        specifier: ^2.0.0
        version: 2.0.0

packages:

  loose-envify@1.4.0:
    resolution: {integrity: sha512-x}
    hasBin: true

  ms@2.0.0:
    resolution: {integrity: sha512-y}

  ms@2.1.3:
    resolution: {integrity: sha512-z}

  react@18.2.0:
    resolution: {integrity: sha512-r}

  '@babel/core@7.24.0':
    resolution: {integrity: sha512-b}
`;

const PNPM_6 = `lockfileVersion: '6.0'

dependencies:
  react:
    specifier: ^18.0.0
    version: 18.2.0

packages:

  /react@18.2.0:
    resolution: {integrity: sha512-r}

  /js-tokens@4.0.0:
    resolution: {integrity: sha512-j}

  /@scope/peer@1.0.0(react@18.2.0):
    resolution: {integrity: sha512-p}
`;

const PNPM_5 = `lockfileVersion: 5.4

specifiers:
  react: ^18.0.0

dependencies:
  react: 18.2.0

packages:

  /react/18.2.0:
    resolution: {integrity: sha512-r}

  /@scope/name/1.2.3_react@18.2.0:
    resolution: {integrity: sha512-s}
`;

const YARN_1 = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.10.4":
  version "7.12.13"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.12.13.tgz#abc"
  integrity sha512-x

ms@^2.0.0:
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/ms/-/ms-2.0.0.tgz#def"

ms@^2.1.1:
  version "2.1.3"
`;

const YARN_BERRY = `__metadata:
  version: 8
  cacheKey: 10c0

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  languageName: unknown

"ms@npm:^2.0.0":
  version: 2.0.0
  resolution: "ms@npm:2.0.0"

"js-tokens@npm:^3.0.0 || ^4.0.0, js-tokens@npm:^4.0.0":
  version: 4.0.0
  resolution: "js-tokens@npm:4.0.0"
`;

test('pnpm-lock.yaml (v9): each importer\'s direct dependencies, and the packages locked in one version', () => {
  const pins = lockPins({ 'pnpm-lock.yaml': PNPM_9 })!;
  assert.equal(pins.source, 'pnpm-lock.yaml');
  assert.equal(pins.direct('', 'react', '^18.2.0'), '18.2.0');
  assert.equal(pins.direct('', 'react-dom', '^18.2.0'), '18.2.0', 'without the peer suffix');
  assert.equal(pins.direct('', 'vite', '^5.0.0'), '5.4.0');
  assert.equal(pins.direct('packages/ui', 'ms', '^2.0.0'), '2.0.0');
  assert.equal(pins.direct('', '@acme/ui', 'workspace:*'), null, 'a link is not a version');
  // A range in package.json the locked version does not satisfy: the lockfile is older; not pinned.
  assert.equal(pins.direct('', 'react', '^19.0.0'), null);
  assert.equal(pins.direct('', 'missing', '^1.0.0'), null);
  assert.deepEqual(pins.single, { '@babel/core': '7.24.0', 'loose-envify': '1.4.0', react: '18.2.0' });
});

test('pnpm-lock.yaml v6 and v5 keys and importers', () => {
  const v6 = lockPins({ 'pnpm-lock.yaml': PNPM_6 })!;
  assert.equal(v6.direct('', 'react', '^18.0.0'), '18.2.0');
  assert.deepEqual(v6.single, { '@scope/peer': '1.0.0', 'js-tokens': '4.0.0', react: '18.2.0' });
  const v5 = lockPins({ 'pnpm-lock.yaml': PNPM_5 })!;
  assert.equal(v5.direct('', 'react', '^18.0.0'), '18.2.0');
  assert.deepEqual(v5.single, { '@scope/name': '1.2.3', react: '18.2.0' });
});

test('yarn.lock, classic and berry: by descriptor', () => {
  const classic = lockPins({ 'yarn.lock': YARN_1 })!;
  assert.equal(classic.source, 'yarn.lock');
  assert.equal(classic.direct('', 'ms', '^2.0.0'), '2.0.0');
  assert.equal(classic.direct('any/dir', '@babel/code-frame', '^7.10.4'), '7.12.13');
  assert.equal(classic.direct('', 'ms', '^3.0.0'), null);
  assert.deepEqual(classic.single, { '@babel/code-frame': '7.12.13' });
  const berry = lockPins({ 'yarn.lock': YARN_BERRY })!;
  assert.equal(berry.direct('', 'ms', '^2.0.0'), '2.0.0');
  assert.equal(berry.direct('', 'js-tokens', '^3.0.0 || ^4.0.0'), '4.0.0');
  assert.deepEqual(berry.single, { 'js-tokens': '4.0.0', ms: '2.0.0' });
});

test('a package-lock.json wins: the other lockfiles are not read', () => {
  assert.equal(lockPins({ 'package-lock.json': '{}', 'pnpm-lock.yaml': PNPM_9 }), null);
  assert.equal(lockPins({ 'npm-shrinkwrap.json': '{}', 'yarn.lock': YARN_1 }), null);
  assert.equal(lockPins({}), null);
  assert.equal(lockPins({ 'pnpm-lock.yaml': 'not: a lockfile' }), null);
});

test('the plan pins direct dependencies and overrides the single-version packages it does not name itself', () => {
  const pkg: PackageJson = { name: 'app', dependencies: { react: '^18.2.0', 'react-dom': '^18.2.0', '@acme/ui': 'workspace:*' }, devDependencies: { vite: '^5.0.0' }, overrides: { 'loose-envify': '1.3.0' } };
  const files = {
    'package.json': JSON.stringify(pkg),
    'pnpm-workspace.yaml': 'packages:\n  - packages/*\n',
    'packages/ui/package.json': JSON.stringify({ name: '@acme/ui', dependencies: { ms: '^2.0.0' } }),
    'pnpm-lock.yaml': PNPM_9,
  };
  const p = installPlan(files, pkg);
  assert.equal(p.pinned, 'pnpm-lock.yaml');
  assert.deepEqual(p.root.dependencies, { react: '18.2.0', 'react-dom': '18.2.0', ms: '2.0.0' });
  assert.deepEqual(p.root.devDependencies, { vite: '5.4.0' });
  // react is a direct dependency (npm refuses an override that differs from it), loose-envify the project's own override.
  assert.deepEqual(p.root.overrides, { '@babel/core': '7.24.0', 'loose-envify': '1.3.0' });
});

test('a yarn.lock pins a project without local packages; without pins the plan reports none', () => {
  const pkg: PackageJson = { dependencies: { ms: '^2.0.0' } };
  const p = installPlan({ 'package.json': JSON.stringify(pkg), 'yarn.lock': YARN_1 }, pkg);
  assert.deepEqual(p.root.dependencies, { ms: '2.0.0' });
  assert.equal(p.pinned, 'yarn.lock');
  const stale = installPlan({ 'package.json': '{}', 'yarn.lock': 'ms@^1.0.0:\n  version "1.0.0"\n' }, { dependencies: { ms: '^2.0.0' } });
  assert.deepEqual(stale.root.dependencies, { ms: '^2.0.0' });
  assert.equal(stale.pinned, null);
});
